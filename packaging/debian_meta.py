#!/usr/bin/env python3
"""Debian metadata for the Vizanti packages, used by build_debs.sh.

bloom-generate only carries the first <maintainer> of package.xml into debian/ and writes a
placeholder copyright file. This fills in who packages Vizanti and who wrote it:

  rosdep-yaml DISTRO REPO        rosdep rules for keys the public rosdep database lacks
  fix-debian  DEBIAN_DIR REPO    rewrite control, copyright and changelog in a bloom debian/ dir
"""

import os
import re
import subprocess
import sys

# who builds and maintains these packages
PACKAGER = "Bruk Gebregziabher <bruk@signalbotics.com>"
PACKAGER_ORG = "Signalbotics"
# who wrote Vizanti
UPSTREAM = "Vid Rijavec (MoffKalast) <vid.rijavec@gmail.com>"
UPSTREAM_CO = "Alastair Bradford <albradford2468@gmail.com>"
UPSTREAM_URL = "https://github.com/MoffKalast/vizanti"
UPSTREAM_YEAR = "2023"
PACKAGING_YEAR = "2026"

PACKAGES = ["vizanti_msgs", "vizanti_server", "vizanti", "vizanti_cpp", "vizanti_demos", "vizanti_nav2", "vizanti_moveit"]

# Third-party code vendored into a package: (package, file globs, its license file, license).
# Copyright holders and the license text are read from the license file it ships with.
THIRD_PARTY = [
    ("vizanti_server", "public/js/lib/three.module.min.js public/js/lib/three_addons/*",
     "public/js/lib/three_LICENSE.txt", "MIT"),
    ("vizanti_server", "public/js/lib/dockview-core.min.js", "public/js/lib/dockview_LICENSE.txt", "MIT"),
    ("vizanti_server", "public/js/lib/roslib.min.js", "public/js/lib/roslibjs_LICENSE.txt", "BSD-3-Clause"),
    ("vizanti_server", "public/js/lib/nipplejs.js public/js/lib/nipplejs.min.js",
     "public/js/lib/nipplejs_LICENSE.txt", "MIT"),
    ("vizanti_server", "public/js/lib/numeric.min.js", "public/js/lib/numericjs_LICENSE.txt", "MIT"),
    ("vizanti_server", "public/js/lib/quaternion.min.js", "public/js/lib/quaternionjs_LICENSE.txt", "MIT"),
]


def copyright_holders(text):
    """The 'Copyright ...' statements of a license file, one per line, without the prefix."""
    holders = []
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if not re.match(r"\s*Copyright\b", line) or "notice" in line:
            continue
        statement = line.strip()
        # a statement may wrap onto the next line (roslibjs)
        if i + 1 < len(lines) and lines[i + 1].strip() and not re.match(r"\s*(Copyright|Permission|Redistribution)", lines[i + 1]):
            statement += " " + lines[i + 1].strip()
        statement = re.sub(r"^Copyright\s*(\(c\)|\(C\)|©)?\s*(by\s+)?", "", statement)
        holders.append(statement)
    return holders


def dep5_text(text):
    """License text as a DEP-5 continuation block: indented, blank lines as ' .'."""
    return "\n".join(" " + line if line.strip() else " ." for line in text.strip().splitlines())


def debian_name(distro, package):
    return f"ros-{distro}-{package.replace('_', '-')}"


def repo_license(repo):
    with open(os.path.join(repo, "LICENSE"), encoding="utf-8") as f:
        text = f.read()
    # the clauses start after the copyright lines
    return text[text.index("Redistribution"):]


# ---------------------------------------------------------------- rosdep rules

def dependency_keys(repo):
    from catkin_pkg.package import parse_package
    keys = set()
    for name in PACKAGES:
        pkg = parse_package(os.path.join(repo, name))
        for group in (pkg.build_depends, pkg.buildtool_depends, pkg.exec_depends,
                      pkg.build_export_depends, pkg.test_depends):
            keys.update(dep.name for dep in group)
    return keys - set(PACKAGES)


def resolves(key, distro):
    return subprocess.run(["rosdep", "resolve", key, "--rosdistro", distro],
                          stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode == 0


def apt_has(package):
    return subprocess.run(["apt-cache", "show", package],
                          stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode == 0


def rosdep_yaml(distro, repo):
    rules = {name: debian_name(distro, name) for name in PACKAGES}
    missing = []
    for key in sorted(dependency_keys(repo)):
        if resolves(key, distro):
            continue
        # a ROS package that is installable from apt but has no rule in rosdep (e.g. nav2_msgs)
        candidate = debian_name(distro, key)
        if apt_has(candidate):
            rules[key] = candidate
        else:
            missing.append(key)
    out = ["# generated by packaging/debian_meta.py"]
    for key, deb in sorted(rules.items()):
        out.append(f"{key}:\n  ubuntu: [{deb}]\n  debian: [{deb}]")
    for key in missing:
        print(f"warning: no rosdep rule or apt package for '{key}'", file=sys.stderr)
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- debian/ files

def fix_control(path, homepage):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    text = re.sub(r"^Maintainer:.*$", f"Maintainer: {PACKAGER}", text, count=1, flags=re.M)
    # the Ubuntu field for "packaged by someone other than the upstream maintainer"
    text = re.sub(r"^(Maintainer:.*)$", rf"\1\nXSBC-Original-Maintainer: {UPSTREAM}", text, count=1, flags=re.M)
    text = re.sub(r"^Homepage:.*$", f"Homepage: {homepage}", text, count=1, flags=re.M)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def fix_copyright(path, package, repo):
    stanzas = [
        "Format: https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/",
        f"Upstream-Name: {package}",
        f"Upstream-Contact: {UPSTREAM}",
        f"Source: {UPSTREAM_URL}",
        "",
        "Files: *",
        f"Copyright: {UPSTREAM_YEAR} {UPSTREAM}",
        f"           {UPSTREAM_CO}",
        f"           {PACKAGING_YEAR} {PACKAGER} ({PACKAGER_ORG})",
        "License: BSD-3-Clause",
        "",
    ]
    package_dir = os.path.join(repo, package)
    for owner, files, license_file, license_name in THIRD_PARTY:
        if owner != package:
            continue
        with open(os.path.join(package_dir, license_file), encoding="utf-8") as f:
            text = f.read()
        holders = copyright_holders(text)
        stanzas += [f"Files: {files}", "Copyright: " + "\n           ".join(holders),
                    f"License: {license_name}", dep5_text(text), ""]
    stanzas += [
        "Files: debian/*",
        f"Copyright: {PACKAGING_YEAR} {PACKAGER} ({PACKAGER_ORG})",
        "License: BSD-3-Clause",
        "",
        "License: BSD-3-Clause",
        dep5_text(repo_license(repo)),
    ]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(stanzas) + "\n")


def fix_changelog(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    credit = (f"  * Vizanti by {PACKAGER} ({PACKAGER_ORG}): the RViz-style 3D interface, plugins and packaging\n"
              f"  * Built on the original Vizanti by {UPSTREAM}, {UPSTREAM_URL}\n")
    # after the blank line that follows each entry's header
    text = re.sub(r"^(\S.*\) .*; urgency=\w+\n\n)", lambda m: m.group(1) + credit, text, flags=re.M)
    # bloom quotes the name in the sign-off line: ' -- "Name" <email>'
    text = re.sub(r'^ -- "([^"]*)" <', r" -- \1 <", text, flags=re.M)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def fix_debian(debian_dir, repo):
    from catkin_pkg.package import parse_package
    package_dir = os.path.dirname(os.path.abspath(debian_dir))
    pkg = parse_package(package_dir)
    homepage = next((u.url for u in pkg.urls if u.type in ("website", "repository")), UPSTREAM_URL)
    fix_control(os.path.join(debian_dir, "control"), homepage)
    fix_copyright(os.path.join(debian_dir, "copyright"), pkg.name, repo)
    fix_changelog(os.path.join(debian_dir, "changelog"))


def main(argv):
    if len(argv) == 4 and argv[1] == "rosdep-yaml":
        sys.stdout.write(rosdep_yaml(argv[2], argv[3]))
    elif len(argv) == 4 and argv[1] == "fix-debian":
        fix_debian(argv[2], argv[3])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv)
